/**
 * Deterministic PRNG using xorshift32 for reproducible stochastic acoustic events.
 */
export class SeededAudioPrng {
  private state: number;

  constructor(seed = 19421202) {
    this.state = (seed === 0 ? 1 : seed) >>> 0;
  }

  public next(): number {
    let x = this.state;
    x ^= x << 13;
    x ^= x >>> 17;
    x ^= x << 5;
    this.state = x >>> 0;
    return (this.state & 0x7fffffff) / 0x7fffffff;
  }
}

/**
 * 1. Bell Telephone Undulating Speech Current Synthesis (US 174,465)
 * Synthesizes vocal acoustic wave modulating electrical current through variable resistance.
 */
export function synthesizeBellSpeechWaveform(
  sampleRate: number,
  durationSec: number,
  fundamentalHz = 220,
  amplitude = 0.5,
  formant1Hz = 700,
  formant2Hz = 1700,
): Float32Array {
  const numSamples = Math.floor(sampleRate * durationSec);
  const buffer = new Float32Array(numSamples);
  const f0 = Math.max(80, Math.min(600, fundamentalHz));
  const amp = Math.max(0, Math.min(1, amplitude));

  for (let i = 0; i < numSamples; i++) {
    const t = i / sampleRate;
    // Glottal fundamental + first two vocal tract formants
    const glottal = Math.sin(2 * Math.PI * f0 * t) + 0.5 * Math.sin(4 * Math.PI * f0 * t);
    const form1 = 0.3 * Math.sin(2 * Math.PI * formant1Hz * t);
    const form2 = 0.15 * Math.sin(2 * Math.PI * formant2Hz * t);

    // Diaphragm displacement x(t)
    const displacement = (glottal + form1 + form2) * 0.5;

    // Undulating current I(t) = V0 / (R0 + Delta R * x(t))
    // Normalized to [-1..1] AC component
    const acCurrent = displacement * amp;

    // Apply smooth envelope attack and release
    const attack = Math.min(1, t / 0.02);
    const release = Math.min(1, (durationSec - t) / 0.03);
    const envelope = attack * release;

    buffer[i] = Math.max(-1, Math.min(1, acCurrent * envelope));
  }

  return buffer;
}

/**
 * 2. Morse Telegraph Armature Strike/Release Synthesis (US 1,647)
 * Synthesizes mechanical impact impulse response of armature striking the anvil stop.
 */
export function synthesizeMorseSounderWaveform(
  sampleRate: number,
  durationSec: number,
  events: Array<{ timeSec: number; type: "strike" | "release"; loopCurrentMa?: number }>,
): Float32Array {
  const numSamples = Math.floor(sampleRate * durationSec);
  const buffer = new Float32Array(numSamples);

  for (const ev of events) {
    const startIdx = Math.floor(ev.timeSec * sampleRate);
    if (startIdx >= numSamples) continue;

    const isStrike = ev.type === "strike";
    const current = Math.max(10, Math.min(100, ev.loopCurrentMa ?? 50));
    const currentScale = Math.sqrt(current / 50);

    const fRes = isStrike ? 800 : 320;
    const decaySec = isStrike ? 0.018 : 0.025;
    const peakAmp = (isStrike ? 0.8 : 0.35) * currentScale;

    const impulseLen = Math.min(numSamples - startIdx, Math.floor(sampleRate * decaySec));
    for (let j = 0; j < impulseLen; j++) {
      const t = j / sampleRate;
      const decay = Math.exp(-t / (decaySec * 0.35));
      const chirp = fRes * (1 - 0.5 * (t / decaySec));
      const sample = peakAmp * decay * Math.sin(2 * Math.PI * chirp * t);
      buffer[startIdx + j] = Math.max(-1, Math.min(1, buffer[startIdx + j] + sample));
    }
  }

  return buffer;
}

/**
 * 3. Marconi Damped Spark Wave Train Synthesis (US 586,193)
 * Synthesizes the acoustic shockwave train from the air expansion in the spark gap.
 */
export function synthesizeMarconiSparkTrainWaveform(
  sampleRate: number,
  durationSec: number,
  sparkRateHz = 120,
  dampingRate = 28,
  intensity = 0.8,
): Float32Array {
  const numSamples = Math.floor(sampleRate * durationSec);
  const buffer = new Float32Array(numSamples);
  const sparkPeriodSec = 1 / Math.max(20, Math.min(500, sparkRateHz));
  const decaySec = Math.max(0.005, Math.min(0.04, 1 / Math.max(1, dampingRate * 2)));

  let nextSparkTime = 0;
  while (nextSparkTime < durationSec) {
    const startIdx = Math.floor(nextSparkTime * sampleRate);
    const sparkLen = Math.min(numSamples - startIdx, Math.floor(sampleRate * decaySec));

    for (let j = 0; j < sparkLen; j++) {
      const t = j / sampleRate;
      const decay = Math.exp(-t / (decaySec * 0.25));
      // Broadband acoustic shockwave chirp with deterministic plasma noise harmonics
      const chirp = 1400 * Math.exp(-t / 0.008) + 180;
      const plasmaNoise = Math.sin(2 * Math.PI * 3141.59 * t) * Math.cos(2 * Math.PI * 1732.05 * t);
      const sample =
        intensity * decay * (Math.sin(2 * Math.PI * chirp * t) * 0.7 + plasmaNoise * 0.3 * decay);
      buffer[startIdx + j] = Math.max(-1, Math.min(1, buffer[startIdx + j] + sample));
    }

    nextSparkTime += sparkPeriodSec;
  }

  return buffer;
}

/**
 * 4. Tesla Resonant Transformer Streamer Synthesis (US 593,138)
 * Synthesizes atmospheric ionization corona buzz and streamer plasma crackle.
 */
export function synthesizeTeslaCoilStreamerWaveform(
  sampleRate: number,
  durationSec: number,
  breakRateHz = 120,
  terminalVoltageKv = 200,
  intensity = 0.7,
): Float32Array {
  const numSamples = Math.floor(sampleRate * durationSec);
  const buffer = new Float32Array(numSamples);
  const fBreak = Math.max(30, Math.min(400, breakRateHz));
  const voltScale = Math.min(1.2, Math.max(0.2, terminalVoltageKv / 150));

  for (let i = 0; i < numSamples; i++) {
    const t = i / sampleRate;
    // Primary interrupter harmonic cascade (f, 2f, 3f, 4f)
    const h1 = Math.sin(2 * Math.PI * fBreak * t);
    const h2 = 0.5 * Math.sin(4 * Math.PI * fBreak * t);
    const h3 = 0.25 * Math.sin(6 * Math.PI * fBreak * t);
    const h4 = 0.12 * Math.sin(8 * Math.PI * fBreak * t);

    // Ionization plasma streamer crackle overtones (1800 Hz - 3200 Hz)
    const plasmaCrackle =
      0.2 * Math.sin(2 * Math.PI * 2400 * t + Math.sin(2 * Math.PI * 60 * t) * 2.0);

    const val = (h1 + h2 + h3 + h4 + plasmaCrackle) * 0.45 * voltScale * intensity;
    buffer[i] = Math.max(-1, Math.min(1, val));
  }

  return buffer;
}

/**
 * 5. Lamarr-Antheil 88-Key Carrier Hop Sequence Synthesis (US 2,292,387)
 * Synthesizes precise equal-tempered musical tones for active perforated record channels.
 */
export function synthesizeLamarrHopSequenceWaveform(
  sampleRate: number,
  hopTape: Array<{ channelIndex: number; durationSec: number }>,
): Float32Array {
  let totalDuration = 0;
  for (const hop of hopTape) totalDuration += hop.durationSec;
  const numSamples = Math.floor(sampleRate * totalDuration);
  const buffer = new Float32Array(numSamples);

  let currentSample = 0;
  for (const hop of hopTape) {
    const channel = Math.max(0, Math.min(87, hop.channelIndex));
    // 88-key piano frequency formula: f = 440 * 2^((n - 49) / 12)
    const frequencyHz = 440 * 2 ** ((channel - 49) / 12);
    const hopSampleCount = Math.floor(hop.durationSec * sampleRate);

    for (let j = 0; j < hopSampleCount && currentSample < numSamples; j++) {
      const t = j / sampleRate;
      // Piano-like envelope: fast attack, exponential decay
      const attack = Math.min(1, t / 0.008);
      const decay = Math.exp(-t / (hop.durationSec * 0.8));
      const envelope = attack * decay * 0.6;

      const sample = envelope * Math.sin(2 * Math.PI * frequencyHz * t);
      buffer[currentSample++] = Math.max(-1, Math.min(1, sample));
    }
  }

  return buffer;
}

/**
 * 6. Fermi Radiation Ionization Click Train Synthesis (US 2,708,656)
 * Deterministic Poisson event generation using SeededAudioPrng.
 */
export function synthesizeFermiRadiationClickWaveform(
  sampleRate: number,
  durationSec: number,
  kEffective = 1.0,
  seed = 19421202,
): Float32Array {
  const numSamples = Math.floor(sampleRate * durationSec);
  const buffer = new Float32Array(numSamples);
  const prng = new SeededAudioPrng(seed);

  // Mean click rate scales exponentially with criticality (kEff - 1)
  const meanRateHz = Math.max(5, Math.min(400, 25 * Math.exp((kEffective - 1.0) * 15)));
  const clickDurationSec = 0.006;
  const clickSamples = Math.floor(sampleRate * clickDurationSec);

  let t = 0;
  while (t < durationSec) {
    // Exponential inter-arrival time: Delta t = -ln(U) / lambda
    const u = Math.max(1e-6, prng.next());
    const dt = -Math.log(u) / meanRateHz;
    t += dt;
    if (t >= durationSec) break;

    const startIdx = Math.floor(t * sampleRate);
    const clickPitch = 1400 + prng.next() * 400;

    for (let j = 0; j < clickSamples && startIdx + j < numSamples; j++) {
      const tau = j / sampleRate;
      const decay = Math.exp(-tau / 0.0015);
      const sample = 0.5 * decay * Math.sin(2 * Math.PI * clickPitch * tau);
      buffer[startIdx + j] = Math.max(-1, Math.min(1, buffer[startIdx + j] + sample));
    }
  }

  return buffer;
}

/**
 * Look up the descriptor for an audio transducer.
 */
export function getAudioTransducerDescriptor(
  transducerId: string,
): AudioTransducerDescriptor | undefined {
  return Object.values(ADMITTED_AUDIO_TRANSDUCERS).find((d) => d.transducerId === transducerId);
}

/**
 * Compute root-mean-square (RMS) energy of an audio buffer.
 */
export function computeAudioBufferRms(buffer: Float32Array): number {
  if (buffer.length === 0) return 0;
  let sumSq = 0;
  for (let i = 0; i < buffer.length; i++) {
    sumSq += buffer[i] * buffer[i];
  }
  return Math.sqrt(sumSq / buffer.length);
}
